<?php
/**
 * Asterisk config hook: needs "sync_domain" in plugin.json. Runs after the
 * core writes and reloads that domain (here general_dialplan), on Apply and on
 * a full sync. Write only files named
 *   extensions_plugin_<slug>.conf, pjsip_plugin_<slug>.conf, hep_plugin_<slug>.conf
 * in /etc/asterisk/pbx/: they are included by the core configuration and removed
 * when the plugin is disabled or uninstalled. The core has already reloaded,
 * so reload what you changed yourself.
 *
 * The context below is not referenced by any route, so it never runs. To try
 * it, point a Custom destination at <slug>-hello,s,1 (sample-plugin-hello,s,1).
 */
return static function (string $slug, array $settings): void {
    $conf = "; Generated by the {$slug} plugin. Do not edit: the next Apply overwrites it.\n"
        . "\n"
        . "[{$slug}-hello]\n"
        . 'exten => s,1,NoOp(Sample plugin: ${CALLERID(num)})' . "\n"
        . " same => n,Answer()\n"
        . " same => n,Playback(hello-world)\n"
        . " same => n,Hangup()\n";
    writePBXConf("extensions_plugin_{$slug}.conf", $conf);
    AsteriskHelper::reloadDialplan();
};
