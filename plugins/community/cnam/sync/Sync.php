<?php

declare(strict_types=1);

/**
 * Asterisk dialplan hook for CNAM plugin.
 * Generates /etc/asterisk/pbx/extensions_plugin_cnam.conf with [sub-cnam-lookup].
 */
return static function (string $slug, array $settings): void {
    $overwrite = !empty($settings['overwrite_existing']);
    $timeout = 2; // Strict 2-second timeout so calls are never delayed

    $conf = "; Generated by the {$slug} plugin. Do not edit: the next Apply overwrites it.\n\n"
        . "[sub-cnam-lookup]\n"
        . "exten => s,1,NoOp(CNAM lookup: caller=\${CALLERID(num)}, name=\${CALLERID(name)})\n"
        . " same => n,Set(LOCAL(cnum)=\${FILTER(0-9+,\${CALLERID(num)})})\n"
        . " same => n,GotoIf(\$[\"\${LOCAL(cnum)}\" = \"\"]?done)\n";

    if (!$overwrite) {
        // Skip lookup if caller name is already present and differs from the number
        $conf .= " same => n,GotoIf(\$[\"\${CALLERID(name)}\" != \"\" & \"\${CALLERID(name)}\" != \"\${CALLERID(num)}\"]?done)\n";
    }

    $conf .= " same => n,Set(CURLOPT(conntimeout)={$timeout})\n"
        . " same => n,Set(CURLOPT(httptimeout)={$timeout})\n"
        . " same => n,Set(LOCAL(cname)=\${CURL(http://127.0.0.1/api/plugins/cnam/lookup?num=\${LOCAL(cnum)})})\n"
        . " same => n,GotoIf(\$[\"\${LOCAL(cname)}\" = \"\"]?done)\n"
        . " same => n,Set(CALLERID(name)=\${LOCAL(cname)})\n"
        . " same => n,NoOp(CNAM lookup success: \${CALLERID(name)})\n"
        . " same => n(done),Return()\n";

    writePBXConf("extensions_plugin_{$slug}.conf", $conf);
    AsteriskHelper::reloadDialplan();
};
